#!/bin/bash
# Упрямое скачивание: рвётся связь - пробуем снова, и так пока не заберём всё.
#
# Владелец сидит на раздаче с телефона (адрес 172.20.10.x). Восемь с половиной
# гигабайт через такое соединение одним куском не проходят: gh качает архив
# целиком, на разрыве бросает его и НИЧЕГО не сохраняет. Пять попыток подряд
# закончились нулём.
#
# Здесь каждый архив качается отдельно и с повторами. Уже скачанное
# пропускаем, поэтому скрипт можно запускать сколько угодно раз: он доберёт
# только недостающее.
cd /Volumes/T7/reels-saas || exit 1
BAZA=/Volumes/T7/ibook-reels/novye
POPYTOK=${POPYTOK:-12}

# Прогоны пересборки: восемь штук, по два на язык.
PROGONY="31767390995:kk 31767394326:kk 31767397573:en 31767400922:en \
         31767404345:de 31767408126:de 31767411322:zh 31767414816:zh"

for PARA in $PROGONY; do
  ID=${PARA%%:*}; L=${PARA##*:}
  KUDA="$BAZA/$L"
  mkdir -p "$KUDA"
  METKA="$KUDA/.gotovo_$ID"
  if [ -f "$METKA" ]; then
    echo "$ID ($L): уже забран, пропускаю"
    continue
  fi
  for i in $(seq 1 "$POPYTOK"); do
    echo "$ID ($L): попытка $i"
    if gh run download "$ID" -n roliki -D "$KUDA" 2>&1 | tail -1; then
      # gh возвращает успех и когда файлы уже лежат - считаем по факту.
      if [ "$(ls "$KUDA"/*.mp4 2>/dev/null | wc -l)" -gt 0 ]; then
        touch "$METKA"
        echo "$ID ($L): забран, на диске $(ls "$KUDA"/*.mp4 | wc -l)"
        break
      fi
    fi
    # На мобильном интернете паузу держим подольше: связь возвращается не сразу.
    sleep $((20 * i))
  done
done

echo "=== ИТОГО ==="
for L in kk en de zh; do
  echo "$L: $(ls "$BAZA/$L"/*.mp4 2>/dev/null | wc -l)"
done
du -sh "$BAZA"
