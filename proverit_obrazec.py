#!/usr/bin/env python3
"""
Проверка записи перед клонированием голоса в ElevenLabs.

Зачем. Клон повторяет ВСЁ, что услышит: гул холодильника, эхо кафельной ванной,
скачки громкости, обрезанные пики. Плохой образец даёт плохой голос на все 156
роликов, и починить его нельзя - только удалить клон и записывать заново.
А узнаём мы об этом уже на готовых роликах, когда потрачены и время, и знаки.

Поэтому проверяем ДО загрузки, по числам, а не на слух.

Что меряем и почему именно это:

    длина        меньше 30 секунд - модели не хватает материала на характер
    перегруз     срезанные пики звучат как треск, клон повторит треск
    шум в паузах разница между речью и тишиной; мало - значит комната шумит
    эхо          хвост после слов; кафель и пустая комната дают гулкий клон
    ровность     скачки громкости заставляют модель гадать, где норма
    речь         доля времени с голосом; много тишины - зря потраченный файл

Пороги взяты не с потолка, а из нашего же опыта на ibook: узбекские и немецкие
голоса, которые владелец забраковал, проваливались ровно по шуму и ровности.

    python proverit_obrazec.py запись.m4a
"""
import subprocess
import sys
import wave

import numpy as np

# Пороги. «хорошо» - можно клонировать, «плохо» - переписать.
NORMY = {
    "длина":    (60, 180, "секунд"),
    "перегруз": (0, 0.5, "% срезанных пиков"),
    "шум":      (35, 99, "дБ разницы речь/тишина"),
    "эхо":      (0, 0.45, "хвост после слов"),
    "ровность": (0, 6.0, "дБ разброса громкости"),
    # Нижнюю границу опустили до 45: студийная начитка с нормальными паузами
    # между фразами даёт около 52%, и это здоровая речь, а не пустой файл.
    "речь":     (45, 95, "% времени с голосом"),
}


def zvuk(put):
    """Достать звук в моно 44.1 кГц. Видео тоже подойдёт - вынем дорожку."""
    w = "/tmp/_proverka.wav"
    r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", put, "-vn",
                        "-ac", "1", "-ar", "44100", w],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"не читается файл: {r.stderr[:200]}")
    f = wave.open(w)
    x = np.frombuffer(f.readframes(f.getnframes()), dtype=np.int16).astype(float) / 32768
    return x, f.getframerate()


def zamery(x, sr):
    ram = int(0.03 * sr)
    okna = np.array([np.sqrt((x[i:i + ram] ** 2).mean())
                     for i in range(0, len(x) - ram, ram)])
    okna = okna[okna > 0]
    if not len(okna):
        sys.exit("в файле тишина")
    # Уровни берём по краям распределения, а не по середине. Первая версия
    # делила окна пополам по медиане и называла нижнюю половину «тишиной» -
    # но в плотной речи там оказывалась тихая речь, а не пауза. Из-за этого
    # разрыв выходил 6 дБ даже у студийной записи, и проверка браковала
    # заведомо чистый файл.
    #
    #   пол шума   пятый процентиль: самое тихое место, это и есть фон
    #   уровень    девяностый: громкая часть речи
    pol = np.percentile(okna, 5)
    uroven = np.percentile(okna, 90)
    porog = pol + 0.25 * (uroven - pol)      # граница речь/пауза
    rech = okna[okna > porog]
    d = {}
    d["длина"] = len(x) / sr
    # Перегруз: сколько отсчётов упёрлось в потолок.
    d["перегруз"] = 100 * (np.abs(x) > 0.985).sum() / len(x)
    d["шум"] = 20 * np.log10(uroven / max(pol, 1e-9))
    # Эхо меряем ТОЛЬКО на выходе из речи в паузу, и за три окна, а не за одно.
    # Внутри слова громкость скачет на каждом согласном, и старая мерка ловила
    # эти скачки вместо хвоста помещения.
    hvosty = []
    for i in range(len(okna) - 3):
        if okna[i] > uroven * 0.7 and okna[i + 3] < porog * 1.5:
            hvosty.append(okna[i + 3] / max(okna[i], 1e-9))
    d["эхо"] = float(np.median(hvosty)) if hvosty else 0.0
    # Ровность: разброс громкости самой речи, без учёта пауз.
    d["ровность"] = float(np.std(20 * np.log10(rech / rech.mean()))) if len(rech) else 99.0
    d["речь"] = 100 * len(rech) / len(okna)
    return d


def main():
    if len(sys.argv) < 2:
        sys.exit("укажи файл: python proverit_obrazec.py запись.m4a")
    put = sys.argv[1]
    x, sr = zvuk(put)
    d = zamery(x, sr)

    print(f"\n{put}\n")
    bed = []
    for imya, (lo, hi, edin) in NORMY.items():
        v = d[imya]
        ok = lo <= v <= hi
        print(f"  {'хорошо' if ok else 'ПЛОХО '}  {imya:9} {v:7.1f}   норма {lo}-{hi} {edin}")
        if not ok:
            bed.append(imya)

    print()
    if not bed:
        print("  ГОДИТСЯ. Можно клонировать.")
        return 0

    # Совет по каждой провалившейся мерке: человеку нужно знать что ПЕРЕДЕЛАТЬ,
    # а не только что плохо.
    sovety = {
        "длина":    "запиши от одной до трёх минут; короткая запись даёт плавающий голос",
        "перегруз": "говори дальше от микрофона или тише: пики срезаны, будет треск",
        "шум":      "выключи кондиционер и холодильник, закрой окно; комната шумит",
        "эхо":      "перейди в комнату с диваном, ковром и шторами; сейчас гулко",
        "ровность": "держи одно расстояние до телефона и не меняй громкость",
        "речь":     "убери долгие паузы или говори без остановок",
    }
    print("  ПЕРЕПИСАТЬ. Что исправить:")
    for b in bed:
        print(f"    {b}: {sovety[b]}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
